update public.menus m
set data = jsonb_set(
  -- Ohne Fußnote bleibt data, wie es ist (jsonb_strip_nulls statt jsonb_set mit NULL).
  m.data || jsonb_strip_nulls(jsonb_build_object('footnote', replace(m.data->>'footnote', '(Wikimedia Commons)', '(Wikimedia Commons und Flickr)'))),
  '{categories}', coalesce((
  select jsonb_agg(jsonb_set(c, '{items}', (
    select coalesce(jsonb_agg(case when f.img is not null and not (i ? 'img') then i || jsonb_build_object('img', f.img) else i end order by io), '[]'::jsonb)
    from jsonb_array_elements(c->'items') with ordinality as y(i, io)
    left join fotos f on f.name = i->>'name'
  )) order by co)
  from jsonb_array_elements(m.data->'categories') with ordinality as x(c, co)
), '[]'::jsonb))
where m.slug = 'divan';
